#!/usr/bin/env bash
# One-time setup: installs build dependencies, depot_tools and the Chromium
# source (~35 GB download, ~100 GB disk after a build), then applies NeoWeb's
# customizations.
#
#   ./setup.sh                    latest Chromium from CHROMIUM_CHANNEL
#   ./setup.sh --version 140.0.7339.80
#   ./setup.sh --skip-deps        don't install system packages
source "$(dirname "$0")/scripts/common.sh"

version=""
skip_deps=0
while (($#)); do
  case "$1" in
    --version) version="$2"; shift 2 ;;
    --skip-deps) skip_deps=1; shift ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) die "Unknown option: $1" ;;
  esac
done

install_system_deps() {
  local sudo=""
  ((EUID)) && sudo="sudo"
  if command -v pacman >/dev/null; then
    log "Installing build dependencies (pacman)"
    $sudo pacman -S --needed --noconfirm base-devel git python curl gperf \
      lsb-release unzip xz pkgconf librsvg imagemagick nss gtk3 alsa-lib
  elif command -v dnf >/dev/null; then
    log "Installing build dependencies (dnf)"
    $sudo dnf install -y git python3 curl gperf unzip xz pkgconf-pkg-config \
      librsvg2-tools ImageMagick gcc gcc-c++ make nss gtk3 alsa-lib
  elif command -v apt-get >/dev/null; then
    log "Installing tools (apt); Chromium's own dependency script runs after download"
    $sudo apt-get update
    $sudo apt-get install -y git python3 curl lsb-release librsvg2-bin imagemagick
  else
    warn "Unknown distribution; install git, python3, curl, gperf, librsvg and imagemagick yourself."
  fi
}

((skip_deps)) || install_system_deps
for tool in git python3 curl rsvg-convert; do
  command -v "$tool" >/dev/null || die "'$tool' is required but not installed."
done

if [[ -d "$DEPOT_TOOLS/.git" ]]; then
  log "Updating depot_tools"
  git -C "$DEPOT_TOOLS" pull -q --ff-only || warn "Could not update depot_tools"
else
  log "Downloading depot_tools"
  git clone -q https://chromium.googlesource.com/chromium/tools/depot_tools.git "$DEPOT_TOOLS"
fi
DEPOT_TOOLS_UPDATE=1 "$DEPOT_TOOLS/update_depot_tools" >/dev/null 2>&1 || true

[[ -n "$version" ]] || version="$(current_version || true)"
[[ -n "$version" ]] || version="$(latest_version)" || die "Could not look up the latest Chromium version."
log "Chromium version: $version"

mkdir -p "$CHROMIUM_DIR"
cat >"$CHROMIUM_DIR/.gclient" <<'EOF'
# Generated by NeoWeb setup.sh. "managed": False because NeoWeb's scripts pick
# the Chromium version themselves (see update.sh).
solutions = [
  {
    "name": "src",
    "url": "https://chromium.googlesource.com/chromium/src.git",
    "managed": False,
    "custom_deps": {},
    "custom_vars": {},
  },
]
EOF

# A missing base tag means no download has finished yet (e.g. an interrupted
# earlier run), so (re)start it.
if ! sgit rev-parse -q --verify "refs/tags/$BASE_TAG" >/dev/null 2>&1; then
  log "Downloading Chromium $version source (a few GB; this takes a while)"
  fetch_chromium_tag "$version"
  sgit tag -f "$BASE_TAG" "$version^{commit}" >/dev/null
  sgit checkout -q -B "$BRANCH" "$BASE_TAG"
  echo "$version" >"$VERSION_FILE"
else
  log "Chromium checkout already exists ($(current_version)); use ./update.sh to change versions"
fi

log "Downloading Chromium dependencies and toolchains (gclient sync)"
(cd "$CHROMIUM_DIR" && gclient sync -D --no-history --shallow)

if command -v apt-get >/dev/null && ((!skip_deps)); then
  log "Running Chromium's install-build-deps.sh"
  sudo "$SRC/build/install-build-deps.sh" --no-prompt
fi

needs_apply && "$NEOWEB_ROOT/apply.sh"
log "Setup done. Next: ./build.sh, then ./run.sh"
